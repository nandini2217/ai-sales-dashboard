"""
autoreport.py
Scheduled version of the pipeline: computes metrics, generates the AI
report, saves a dated copy to output/, and emails it. Run this from cron /
Task Scheduler / GitHub Actions for the "weekly report" use case described
in the README. For a one-off report without email, use insight_generator.py.
"""
