def build_text_email(m: dict, ai_report: str, today: str) -> str:
    return f"""
Weekly Business Insight Report
Generated: {today}
{'=' * 50}

KEY METRICS SUMMARY:
- Total Sales:    ${m['total_sales']:,.2f}
- Total Profit:   ${m['total_profit']:,.2f}
- Profit Margin:  {m['profit_margin']:.2f}%
- Total Orders:   {m['total_orders']:,}
- Top Region:     {m['top_region']}
- Loss Areas:     {m['loss_list']}

{'=' * 50}
AI GENERATED INSIGHTS:

{ai_report}

{'=' * 50}
This report was automatically generated by the sales insight pipeline.
"""


def send_email(sender_email, sender_password, receiver_email, subject, text_body, html_body):
    msg = MIMEMultipart("alternative")
    msg["Subject"] = subject
    msg["From"] = sender_email
    msg["To"] = receiver_email
    msg.attach(MIMEText(text_body, "plain"))
    msg.attach(MIMEText(html_body, "html"))

    with smtplib.SMTP_SSL("smtp.gmail.com", 465) as server:
        server.login(sender_email, sender_password)
        server.sendmail(sender_email, receiver_email, msg.as_string())


def main():
    df = load_data()
    m = compute_metrics(df)
    print(format_metrics_summary(m))
    print("Step 1: Metrics calculated successfully")

    client = Groq(api_key=os.getenv("GROQ_API_KEY"))
    ai_report = generate_ai_report(client, m)
    print("Step 2: AI report generated successfully")

    today = datetime.now().strftime("%Y-%m-%d")
    report_filename = f"output/insight_report_{today}.txt"
    with open(report_filename, "w") as f:
        f.write("WEEKLY BUSINESS INSIGHT REPORT\n")
        f.write(f"Generated on: {today}\n")
        f.write("=" * 50 + "\n\n")
        f.write(ai_report)
    print(f"Step 3: Report saved to {report_filename}")

    sender_email = os.getenv("EMAIL_SENDER")
    sender_password = os.getenv("EMAIL_PASSWORD")
    receiver_email = sender_email  # sending to yourself

    text_body = build_text_email(m, ai_report, today)
    html_body = build_html_email(m, ai_report, today)

    try:
        send_email(
            sender_email,
            sender_password,
            receiver_email,
            subject=f"Weekly Business Insight Report — {today}",
            text_body=text_body,
            html_body=html_body,
        )
        print(f"Step 4: Email sent successfully! Check your inbox at {receiver_email}")
    except Exception as e:
        print(f"Email failed: {e}")

    print("\nPipeline complete! Report generated and emailed successfully.")


if __name__ == "__main__":
    main()
